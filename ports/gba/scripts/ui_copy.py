def cstr(s):
    return '"' + ''.join(chr(b) if 32 <= b < 127 and b not in (34, 92) else f'\\{b:03o}' for b in s.encode('cp866')) + '"'

def main():
    out = ["/* GBA menu copy, CP866. Original notification copy stays in ROM textpool. */"]
    for name, values in COPY.items():
        if isinstance(values[0], list):
            assert len(values[0]) == len(values[1])
            body = ','.join('{' + ','.join(map(cstr, row)) + '}' for row in values)
            out.append(f'static const char *const {name}[2][{len(values[0])}]={{{body}}};')
        else:
            out.append(f'static const char *const {name}[2]={{{",".join(map(cstr, values))}}};')
    Path('ports/gba/src/ui_text.inc').write_text('\n'.join(out) + '\n', encoding='ascii')
    # Offline-only tool, shared with the Wonderfield reference (MIT).
    from vendor.nayuki.qrcodegen import QrCode, QrSegment
    url = 'https://t.me/RetroGamingNaBalkone'
    qr = QrCode.encode_segments([QrSegment.make_bytes(url.encode('ascii'))],
        QrCode.Ecc.MEDIUM, minversion=3, maxversion=3, boostecl=False)
    assert qr.get_size() == 29
    bits = bytearray((29*29+7)//8)
    for y in range(29):
        for x in range(29):
            if qr.get_module(x,y):
                at = y*29+x
                bits[at//8] |= 1 << (at%8)
    Path('ports/gba/src/ui_channel_qr.inc').write_text(
        f'/* {url}; QR V3 M, mask {qr.get_mask()}, LSB-first rows.\n'
        ' * Generated by scripts/ui_copy.py; 4-module quiet zone drawn by UI. */\n'
        'static const uint8_t ui_channel_qr[106]={' + ','.join(map(str,bits)) + '};\n'
        'static const char ui_channel_url[]="t.me/RetroGamingNaBalkone";\n', encoding='ascii')

if __name__ == '__main__':
    main()
