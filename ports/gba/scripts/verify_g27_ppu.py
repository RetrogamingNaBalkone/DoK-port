"""Actual mGBA OBJ replay of admitted G27 atlas commands, isolated test display.

This verifies the packet/affine/alpha oracle, not a native renderer or UI timing.
The input texels were generated by production CPU raster before this test.
"""
import json, os, struct, zlib
from pathlib import Path
from check_g27 import ROOT,OUT,BUILD,PIN,pack
from verify_gba_static_cache import Workspace
from research_gba_fps import GameProbe,freeze
from verify_gba import VIDEO,sha

def main():
    data=json.loads(zlib.decompress((OUT/'captures.json.zlib').read_bytes()))
    core=Path(os.environ['LOCALAPPDATA'])/'Programs/mGBA/libretro-20261024/mgba_libretro.dll'
    build=ROOT/'build/gba/g27/ppu/g27_packet_oracle'
    p=GameProbe(core,build);rows=[]
    try:
        p.video_callback=VIDEO(p.frontend.video);p.frontend.core.retro_set_video_refresh(p.video_callback)
        p.until(lambda d:d['draws']>=1);p.write(p.symbols['g_camera_capture_hold'],struct.pack('<I',1))
        p.until(lambda d:d['draws']>=4 and d['phase']==2);freeze(p,True)
        for row in data['rows']:
            layers=[]
            for face in row['faces']:
                if face['object_class']==2:continue
                layer=bytearray(120*128)
                for ci in face['columns']:
                    c=row['columns'][ci]
                    for k,v in enumerate(c['colors']):layer[(c['y']+k)*120+c['x']]=v
                if any(layer):layers.append(layer)
            result=pack(layers,True,True)
            if not result['capacity'] or not result['exact_pixels']:continue
            atlas=bytearray();offsets={};oam=bytearray(1024)
            for idx in range(128):struct.pack_into('<H',oam,idx*8,0x200)
            for idx,cmd in enumerate(result['commands']):
                width=cmd['width']//2;payload=cmd['payload'];key=(width,payload)
                if key not in offsets:
                    offsets[key]=len(atlas)
                    atlas.extend(payload[y*width+tx+x] for tx in range(0,width,8) for y in range(8) for x in range(8))
                a=0x2300|(0x4000 if width>8 else 0)|(cmd['top']&255)
                b=(0x4000 if width==32 else 0)|(cmd['x']&511)
                struct.pack_into('<3H',oam,(64+idx)*8,a,b,offsets[key]//32)
            for off,v in ((6,128),(14,0),(22,0),(30,227)):struct.pack_into('<h',oam,off,v)
            address=p.symbols['g_hw_obj_rows_probe'];request=p.words('g_hw_obj_rows_probe',2)[1]+1
            p.write(p.symbols['g_render_frame']+Workspace.frame.offset,bytes(atlas)+bytes(16384-len(atlas))+bytes(oam))
            p.write(address+8,struct.pack('<I',1));p.write(address,struct.pack('<I',request))
            p.until(lambda d:p.words('g_hw_obj_rows_probe',2)[1]==request)
            p.write(address+8,struct.pack('<I',1));p.frontend.run(3)
            actual=p.frontend.colors555();expected=list(result['expected'])+[0]*(240*16)
            differences=sum(a!=b for a,b in zip(actual,expected));assert len(actual)==38400
            assert differences==0,(row['name'],differences,actual[:10],expected[:10],p.frontend.read(0x04000000,2).hex(),p.frontend.read(0x06010000,16).hex(),bytes(atlas[:16]).hex())
            rows.append(dict(name=row['name'],language=row['language'],objects=result['objects'],atlas_bytes=len(atlas),pixels=38400,differences=differences))
    finally:p.close()
    (OUT/'ppu.json').write_text(json.dumps(dict(status='passed',rom_sha256=sha(build/'dok-diagnostic.gba'),input_rom_sha256=PIN,core_sha256=sha(core),rows=rows,
        scope='Injected admitted merged post-raster commands, IRQ/DMA disabled and BG/UI removed for isolated PPU oracle. Not native performance, full composition or hardware acceptance.'),indent=2)+'\n')
    print('actual PPU',len(rows),'nonempty admitted packets exact')
if __name__=='__main__':main()
