"""Freeze the two matching original RAM trig tables for reproducible platforms."""
import hashlib
import math
from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parents[3]
SAMPLES = [('ru-03', 0x1ca9b0), ('en-02', 0x1ce160)]


def main():
    tables = []
    angles = []
    for profile, address in SAMPLES:
        path = ROOT / 'research/evidence/reference' / profile / 'level1-memory.bin'
        data = path.read_bytes()
        values = struct.unpack_from('<722i', data, address)
        angles.append(struct.unpack_from('<101h', data, address+0xb48))
        expected = tuple(int(fn(angle*3.14159265359/180)*32768)
                         for fn in (math.sin, math.cos) for angle in range(361))
        if values != expected:
            raise RuntimeError('Original table mismatch: ' + profile)
        tables.append(values)
        print(profile, '722 original values verified;', hashlib.sha256(data).hexdigest())
    if tables[0] != tables[1]:
        raise RuntimeError('Original localizations disagree')
    output = ['// Generated by ports/sdl2/tools/generate_trig.py from original DOS RAM.',
              '// Ghidra generator and guest linear addresses: rendering-reference.md.']
    for index, name in enumerate(('sine', 'cosine')):
        output.append('static constexpr std::array<std::int32_t,361> '+name+' = {{')
        values = tables[0][index*361:(index+1)*361]
        for start in range(0, len(values), 12):
            output.append('    '+','.join(map(str,values[start:start+12]))+',')
        output.append('}};')
    (ROOT / 'ports/sdl2/src/trig.inc').write_text('\n'.join(output)+'\n',encoding='utf-8')
    if angles[0] != angles[1] or angles[0][100] != 45:
        raise RuntimeError('Original AI angle tables disagree')
    (ROOT/'ports/sdl2/src/ai_angles.inc').write_text(
        '// Original RAM math-segment +0xb48; RU/EN tables match.\n'
        'static constexpr std::array<std::int16_t,101> angles={{\n'+
        ','.join(map(str,angles[0]))+'\n}};\n',encoding='utf-8')


if __name__ == '__main__':
    main()
