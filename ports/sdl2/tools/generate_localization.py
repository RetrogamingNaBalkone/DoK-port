"""Compile the reviewed UTF-8 catalogue; original RES files are not build inputs."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SOURCE = ROOT / 'ports/sdl2/data/localization.json'
TARGET = ROOT / 'ports/sdl2/src/localization_data.inc'


def generate():
    data = json.loads(SOURCE.read_text(encoding='utf-8'))
    assert data['schema'] == 1
    lines = ['// Generated by tools/generate_localization.py. Edit data/localization.json.',
             'static constexpr TextEntry text_entries[] = {']
    for key, pair in sorted(data['texts'].items()):
        assert pair['ru'] and pair['en']
        for value in pair.values():
            value.encode('cp866')  # Every character is supported by the game fonts.
        lines.append('    {' + ','.join(json.dumps(x, ensure_ascii=False) for x in (key, pair['ru'], pair['en'])) + '},')
    lines += ['};', 'static constexpr AliasEntry alias_entries[] = {']
    for value, key in sorted(data['aliases'].items()):
        assert key in data['texts']
        encoded = ''.join(f'\\x{byte:02x}' for byte in value.encode('cp866'))
        lines.append(f'    {{"{encoded}","{key}"}},')
    lines += ['};', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = generate()
    if args.check:
        assert TARGET.read_text(encoding='utf-8') == expected, 'Regenerate localization_data.inc'
    else:
        TARGET.write_text(expected, encoding='utf-8')
